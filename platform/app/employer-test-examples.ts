import type {
  EmployerTestDefinition,
  EmployerQuestion,
} from "@/lib/employer-test-types";

const choice = (
  kind: "single" | "multiple",
  prompt: string,
  labels: string[],
  correct: number[],
  explanation: string,
): EmployerQuestion => ({
  id: crypto.randomUUID(),
  kind,
  prompt,
  points: 5,
  options: labels.map((label, i) => ({ id: `o${i + 1}`, label })),
  correctOptionIds: correct.map((i) => `o${i}`),
  explanation,
  rubric: "",
});
const text = (prompt: string, rubric: string): EmployerQuestion => ({
  id: crypto.randomUUID(),
  kind: "text",
  prompt,
  points: 10,
  options: [],
  correctOptionIds: [],
  explanation: "",
  rubric,
});
